export function resolveLanguage(_value: unknown): Language {
  return "id";
}

export function t(key: string, language: Language = "id"): string {
  return translations[language][key] ?? translations.id[key] ?? key;
}

export function applyLanguage(_language: Language = "id") {
  const language: Language = "id";
  const root = document.documentElement;
  root.lang = language;
  root.dataset.language = language;
  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  window.dispatchEvent(new CustomEvent("licia:language-change", { detail: language }));
}
